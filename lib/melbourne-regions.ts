import type { Locale } from "@/lib/site-i18n";

/**
 * Region hub model for Melbourne suburbs. There are ~248 active service-area
 * suburbs in `public.suburbs`; rather than a thin page per suburb, we group them
 * into 9 named Melbourne regions. Each region gets ONE rich landing page that
 * lists every suburb it covers (capturing the long-tail "{suburb} second hand"
 * keywords) without hundreds of near-duplicate pages.
 *
 * The 8 existing city/inner suburb pages (CBD, Carlton, Parkville, Southbank,
 * Docklands, Fitzroy, North Melbourne, South Wharf) are kept AS-IS and simply
 * linked from within their region's suburb list (see EXISTING_SUBURB_PAGES).
 *
 * IMPORTANT: `suburbs` entries must exactly match `public.suburbs.name`. The set
 * across all regions must be an exact partition of the active suburbs — verified
 * by scripts against Supabase. Do not edit names casually.
 */

export const REGION_SLUGS = [
  "inner-north",
  "inner-east",
  "inner-south",
  "eastern",
  "south-east",
  "bayside",
  "northern",
  "north-west",
  "western",
] as const;

export type RegionSlug = (typeof REGION_SLUGS)[number];

export type MelbourneRegion = {
  slug: RegionSlug;
  /** Short geographic label per locale, interpolated into page copy. */
  names: Record<Locale, string>;
  /** Exact `public.suburbs.name` values that belong to this region. */
  suburbs: string[];
};

