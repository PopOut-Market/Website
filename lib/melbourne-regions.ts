export function getRegion(slug: string): MelbourneRegion | null {
  return MELBOURNE_REGIONS.find((r) => r.slug === slug) ?? null;
}

/** Logical region paths (locale-less) for sitemap + hub links. */
export function regionPaths(): string[] {
  return MELBOURNE_REGIONS.map((r) => `/melbourne-suburbs/${r.slug}`);
}
